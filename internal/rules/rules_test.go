// file builds a diff.File from lines prefixed with '+', '-' or ' '.
func file(newPath, oldPath string, lines ...string) diff.File {
	f := diff.File{Path: newPath, OldPath: oldPath}
	n := 1
	for _, s := range lines {
		l := diff.Line{Kind: s[0], Text: s[1:]}
		if l.Kind != '-' {
			l.N = n
			n++
		}
		f.Lines = append(f.Lines, l)
	}
	return f
}

func ids(vs []Violation) string {
	var out []string
	for _, v := range vs {
		out = append(out, v.Rule)
	}
	return strings.Join(out, ",")
}

// l10nAt pretends the Flutter app at root has an l10n.yaml.
func l10nAt(root string) func(string) []byte {
	return func(p string) []byte {
		if p == root+"l10n.yaml" {
			return []byte("arb-dir: lib/l10n\n")
		}
		return nil
	}
}

func run(t *testing.T, id string, in Input) []Violation {
	t.Helper()
	rs, unk := Select([]string{id})
	if len(unk) > 0 {
		t.Fatalf("unknown rule %v", unk)
	}
	return Run(rs, in)
}

func TestRules(t *testing.T) {
	cases := []struct {
		name, rule string
		in         Input
		want       int
	}{
		{"bare return err from other package", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "+\tb, err := os.ReadFile(p)", " \tif err != nil {", "+\t\treturn nil, err")}}, 1},
		{"bare return err from method", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "\trows, err := s.db.QueryContext(ctx, q)", "+\t\treturn err")}}, 1},
		{"same-package passthrough ok", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "+\tgot, err := Run(ctx, c)", "+\t\treturn done, err")}}, 0},
		{"local call with qualified args ok", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "+\terr := copyFile(filepath.Join(a, b), c)", "+\t\treturn err")}}, 0},
		{"unknown origin ok", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "+\t\treturn nil, err")}}, 0},
		{"generated go skipped", "go-errors-wrap", Input{Files: []diff.File{file("db/q.sql.go", "db/q.sql.go", "+\trows, err := q.db.QueryContext(ctx, s)", "+\t\treturn nil, err")}}, 0},
		{"wrapped err", "go-errors-wrap", Input{Files: []diff.File{file("q/q.go", "q/q.go", "+\treturn fmt.Errorf(\"q: %w\", err)")}}, 0},
		{"bare err in test ok", "go-errors-wrap", Input{Files: []diff.File{file("q/q_test.go", "q/q_test.go", "+\treturn err")}}, 0},
		{"println in lib", "no-fmt-println", Input{Files: []diff.File{file("internal/q.go", "", "+\tfmt.Println(x)")}}, 1},
		{"println in cmd ok", "no-fmt-println", Input{Files: []diff.File{file("cmd/x/run.go", "", "+\tfmt.Println(x)")}}, 0},
		{"time.Now in test", "go-test-no-time-now", Input{Files: []diff.File{file("a_test.go", "", "+\tnow := time.Now()")}}, 1},
		{"edit migration", "no-edit-migrations", Input{Files: []diff.File{file("db/migrations/001_init.sql", "db/migrations/001_init.sql", "+ALTER TABLE x;")}}, 1},
		{"new migration ok", "no-edit-migrations", Input{Files: []diff.File{file("db/migrations/002_x.sql", "", "+ALTER TABLE x;")}}, 0},
		{"regenerated with sql source ok", "no-edit-generated", Input{Files: []diff.File{
			file("internal/db/q.sql.go", "internal/db/q.sql.go", "+x"), file("internal/db/queries/q.sql", "internal/db/queries/q.sql", "+-- name: X :one")}}, 0},
		{"regenerated dart part ok", "no-edit-generated", Input{Files: []diff.File{
			file("lib/m.g.dart", "lib/m.g.dart", "+x"), file("lib/m.dart", "lib/m.dart", "+  final int y;")}}, 0},
		{"generated by path", "no-edit-generated", Input{Files: []diff.File{file("lib/m.g.dart", "lib/m.g.dart", "+x")}}, 1},
		{"generated by header", "no-edit-generated", Input{
			Files: []diff.File{file("db/q.go", "db/q.go", "+x")},
			Read:  func(string) []byte { return []byte("// Code generated by sqlc. DO NOT EDIT.\npackage db\n") },
		}, 1},
		{"go.mod require", "no-new-deps", Input{Files: []diff.File{file("go.mod", "go.mod", "+\tgithub.com/x/y v1.2.3")}}, 1},
		{"go.mod allowed", "no-new-deps", Input{AllowDeps: true, Files: []diff.File{file("go.mod", "go.mod", "+\tgithub.com/x/y v1.2.3")}}, 0},
		{"go.mod indirect ok", "no-new-deps", Input{Files: []diff.File{file("go.mod", "go.mod", "+\tgithub.com/x/z v0.1.0 // indirect")}}, 0},
		{"pubspec flutter section ok", "no-new-deps", Input{Files: []diff.File{file("pubspec.yaml", "pubspec.yaml", " flutter:", "+  assets:", "+    - assets/x.png")}}, 0},
		{"pubspec dep", "no-new-deps", Input{Files: []diff.File{file("pubspec.yaml", "pubspec.yaml", " dependencies:", "+  dio: ^5.0.0")}}, 1},
		{"code without test", "tests-added", Input{Files: []diff.File{file("q.go", "q.go", "+x := 1")}}, 1},
		{"empty test does not count", "tests-added", Input{Files: []diff.File{
			file("q.go", "q.go", "+x := 1"), file("q_test.go", "", "+func TestQ(t *testing.T) {}")}}, 1},
		{"asserting test", "tests-added", Input{Files: []diff.File{
			file("q.go", "q.go", "+x := 1"), file("q_test.go", "", "+\tif x != 1 { t.Fatalf(\"x\") }")}}, 0},
		{"dart expect", "tests-added", Input{Files: []diff.File{
			file("lib/a.dart", "lib/a.dart", "+int a = 1;"), file("test/a_test.dart", "", "+  expect(a, 1);")}}, 0},
		{"hardcoded text", "flutter-no-hardcoded-text", Input{Read: l10nAt("app/"), Files: []diff.File{file("app/lib/home.dart", "app/lib/home.dart", "+    child: Text('Ahoj světe'),")}}, 1},
		{"l10n text ok", "flutter-no-hardcoded-text", Input{Read: l10nAt(""), Files: []diff.File{file("lib/home.dart", "lib/home.dart", "+    child: Text(l10n.hello),")}}, 0},
		{"app without l10n ok", "flutter-no-hardcoded-text", Input{Files: []diff.File{file("lib/home.dart", "lib/home.dart", "+    child: Text('Ahoj světe'),")}}, 0},
		{"await in build", "flutter-no-logic-in-build", Input{Files: []diff.File{file("lib/p.dart", "lib/p.dart",
			"   @override",
			"   Widget build(BuildContext context) {",
			"+    final r = http.get(uri);",
			"+    return ElevatedButton(onPressed: () async {",
			"+      await http.get(uri);",
			"+    }, child: FutureBuilder(future: api.load(), builder: b));",
			"   }",
			"+  Future<void> load() async { await http.get(uri); }",
		)}}, 2},
		{"release workflow", "no-release-workflow-edit", Input{Files: []diff.File{file(".github/workflows/release-ios.yml", ".github/workflows/release-ios.yml", "+x")}}, 1},
		{"env file", "no-secrets-files", Input{Files: []diff.File{file("backend/.env", "", "+K=v")}}, 1},
		{"env example ok", "no-secrets-files", Input{Files: []diff.File{file(".env.example", "", "+K=")}}, 0},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := run(t, c.rule, c.in)
			if len(got) != c.want {
				t.Fatalf("%s: got %d violations (%s) %+v, want %d", c.rule, len(got), ids(got), got, c.want)
			}
		})
	}
}

func TestAllHaveSource(t *testing.T) {
	for _, r := range All() {
		if r.Source == "" || r.Check == nil {
			t.Errorf("rule %s has no source or check", r.ID)
		}
	}
}
